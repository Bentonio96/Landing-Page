const AGUDO = ["...#.", "..#.."];
const VIRGULILLA = [".##.#", "#..#."];
const NADA = [".....", "....."];

const ACENTOS: Record<string, [string, string[]]> = {
  Á: ["A", AGUDO],
  É: ["E", AGUDO],
  Í: ["I", AGUDO],
  Ó: ["O", AGUDO],
  Ú: ["U", AGUDO],
  Ñ: ["N", VIRGULILLA],
};

export const ALTO_GLIFO = 9;

/** Filas del glifo, ya con las dos de acento arriba. */
export function glifo(caracter: string): string[] {
  const c = caracter.toUpperCase();
  const acento = ACENTOS[c];
  if (acento) return [...acento[1], ...BASE[acento[0]]];
  const base = BASE[c] ?? BASE[" "];
  const vacio = base[0].replace(/#/g, ".");
  return [...(base === BASE[" "] ? [vacio, vacio] : NADA), ...base];
}

export type Punto = { x: number; y: number };

/**
 * Pone varias líneas de texto en una grilla y devuelve los LED encendidos
 * más el tamaño de la grilla, con `margen` celdas apagadas alrededor.
 */
export function componer(lineas: string[], margen = 1, interlinea = 1) {
  const anchoDe = (linea: string) =>
    [...linea].reduce((suma, c) => suma + glifo(c)[0].length, 0) + Math.max(0, [...linea].length - 1);
  const columnas = Math.max(...lineas.map(anchoDe)) + margen * 2;
  const filas = lineas.length * ALTO_GLIFO + (lineas.length - 1) * interlinea + margen * 2;
  const encendidos: Punto[] = [];

  lineas.forEach((linea, l) => {
    let x = margen;
    const y0 = margen + l * (ALTO_GLIFO + interlinea);
    for (const c of linea) {
      const filasGlifo = glifo(c);
      filasGlifo.forEach((fila, dy) => {
        [...fila].forEach((celda, dx) => {
          if (celda === "#") encendidos.push({ x: x + dx, y: y0 + dy });
        });
      });
      x += filasGlifo[0].length + 1;
    }
  });

  return { columnas, filas, encendidos };
}
